func (r *routeSetResource) Configure(_ context.Context, req resource.ConfigureRequest, resp *resource.ConfigureResponse) {
	if req.ProviderData == nil {
		return
	}
	client, ok := req.ProviderData.(*arin.Client)
	if !ok {
		resp.Diagnostics.AddError("Unexpected provider configuration", fmt.Sprintf("Expected *arin.Client, got %T", req.ProviderData))
		return
	}
	r.client = client
}
func (m routeSetModel) api(ctx context.Context) (arin.RouteSet, diag.Diagnostics) {
	s := arin.RouteSet{Name: m.Name.ValueString(), OrgHandle: m.OrgHandle.ValueString()}
	var d diag.Diagnostics
	d.Append(m.Description.ElementsAs(ctx, &s.Description, false)...)
	d.Append(m.Remarks.ElementsAs(ctx, &s.Remarks, false)...)
	d.Append(m.Members.ElementsAs(ctx, &s.Members, false)...)
	d.Append(m.MembersByRef.ElementsAs(ctx, &s.MembersByRef, false)...)
	d.Append(m.MPMembers.ElementsAs(ctx, &s.MPMembers, false)...)

	return s, d
}
func (r *routeSetResource) ValidateConfig(ctx context.Context, req resource.ValidateConfigRequest, resp *resource.ValidateConfigResponse) {
	var m routeSetModel
	resp.Diagnostics.Append(req.Config.Get(ctx, &m)...)
	if resp.Diagnostics.HasError() {
		return
	}
	// Unknown expressions are validated after Terraform resolves the plan.
	for _, v := range []attr.Value{m.Name, m.OrgHandle, m.Description, m.Remarks, m.Members, m.MembersByRef, m.MPMembers} {
		tv, err := v.ToTerraformValue(ctx)
		if err != nil || !tv.IsFullyKnown() {
			return
		}
	}
	s, d := m.api(ctx)
	resp.Diagnostics.Append(d...)
	if !resp.Diagnostics.HasError() {
		if err := s.Validate(); err != nil {
			resp.Diagnostics.AddError("Invalid route set configuration", err.Error())
		}
	}
}
func routeSetState(ctx context.Context, s *arin.RouteSet) (routeSetModel, diag.Diagnostics) {
	m := routeSetModel{ID: types.StringValue(s.Name), Name: types.StringValue(s.Name), OrgHandle: types.StringValue(s.OrgHandle), CreationDate: types.StringNull(), LastModifiedDate: types.StringNull()}
	if s.CreationDate != "" {
		m.CreationDate = types.StringValue(s.CreationDate)
	}
	if s.LastModifiedDate != "" {
		m.LastModifiedDate = types.StringValue(s.LastModifiedDate)
	}
	var d, next diag.Diagnostics
	m.Description, next = types.ListValueFrom(ctx, types.StringType, nonNilStrings(s.Description))
	d.Append(next...)
	m.Remarks, next = types.ListValueFrom(ctx, types.StringType, nonNilStrings(s.Remarks))
	d.Append(next...)
	m.Members, next = types.SetValueFrom(ctx, types.StringType, nonNilStrings(s.Members))
	d.Append(next...)
	m.MembersByRef, next = types.SetValueFrom(ctx, types.StringType, nonNilStrings(s.MembersByRef))
	d.Append(next...)
	m.MPMembers, next = types.SetValueFrom(ctx, types.StringType, nonNilStrings(s.MPMembers))
	d.Append(next...)
	pocs := []irrPOCModel{}
	for _, p := range s.POCs {
		pocs = append(pocs, irrPOCModel{types.StringValue(p.Handle), types.StringValue(p.Function)})
	}
	m.POCs, next = types.SetValueFrom(ctx, irrPOCType, pocs)
	d.Append(next...)
	return m, d
}
func (r *routeSetResource) Create(ctx context.Context, req resource.CreateRequest, resp *resource.CreateResponse) {
	var m routeSetModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &m)...)
	if resp.Diagnostics.HasError() {
		return
	}
	s, d := m.api(ctx)
	resp.Diagnostics.Append(d...)
	if resp.Diagnostics.HasError() {
		return
	}
	result, err := r.client.CreateRouteSet(ctx, s)
	if err != nil {
		resp.Diagnostics.AddError("Could not create route set", err.Error()+". If a write was sent, verify the object before retrying; import it by name if creation succeeded.")
		return
	}
	m, d = routeSetState(ctx, result)
	resp.Diagnostics.Append(d...)
	if !resp.Diagnostics.HasError() {
		resp.Diagnostics.Append(resp.State.Set(ctx, &m)...)
	}
}
func (r *routeSetResource) Read(ctx context.Context, req resource.ReadRequest, resp *resource.ReadResponse) {
	var m routeSetModel
	resp.Diagnostics.Append(req.State.Get(ctx, &m)...)
	if resp.Diagnostics.HasError() {
		return
	}
	result, err := r.client.GetRouteSet(ctx, m.ID.ValueString())
	if arin.IsNotFound(err) {
		resp.State.RemoveResource(ctx)
		return
	}
	if err != nil {
		resp.Diagnostics.AddError("Could not read route set", err.Error())
		return
	}
	m, d := routeSetState(ctx, result)
	resp.Diagnostics.Append(d...)
	if !resp.Diagnostics.HasError() {
		resp.Diagnostics.Append(resp.State.Set(ctx, &m)...)
	}
}
func (r *routeSetResource) Update(ctx context.Context, req resource.UpdateRequest, resp *resource.UpdateResponse) {
	var m routeSetModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &m)...)
	if resp.Diagnostics.HasError() {
		return
	}
	s, d := m.api(ctx)
	resp.Diagnostics.Append(d...)
	if resp.Diagnostics.HasError() {
		return
	}
	result, err := r.client.UpdateRouteSet(ctx, s)
	if err != nil {
		resp.Diagnostics.AddError("Could not update route set", err.Error()+". Refresh the object before retrying an uncertain write.")
		return
	}
	m, d = routeSetState(ctx, result)
	resp.Diagnostics.Append(d...)
	if !resp.Diagnostics.HasError() {
		resp.Diagnostics.Append(resp.State.Set(ctx, &m)...)
	}
}
func (r *routeSetResource) Delete(ctx context.Context, req resource.DeleteRequest, resp *resource.DeleteResponse) {
	var m routeSetModel
	resp.Diagnostics.Append(req.State.Get(ctx, &m)...)
	if resp.Diagnostics.HasError() {
		return
	}
	if err := r.client.DeleteRouteSet(ctx, m.ID.ValueString()); err != nil {
		resp.Diagnostics.AddError("Could not delete route set", err.Error()+". Refresh the object before retrying an uncertain write.")
	}
}
func (r *routeSetResource) ImportState(ctx context.Context, req resource.ImportStateRequest, resp *resource.ImportStateResponse) {
	if err := arin.ValidateRouteSetName(req.ID); err != nil {
		resp.Diagnostics.AddError("Invalid route set import ID", err.Error())
		return
	}
	resource.ImportStatePassthroughID(ctx, path.Root("id"), req, resp)
}
