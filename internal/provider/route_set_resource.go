var (
	_ resource.Resource                   = &routeSetResource{}
	_ resource.ResourceWithConfigure      = &routeSetResource{}
	_ resource.ResourceWithImportState    = &routeSetResource{}
	_ resource.ResourceWithValidateConfig = &routeSetResource{}
)

type routeSetResource struct{ client *arin.Client }
type routeSetModel struct {
	ID               types.String `tfsdk:"id"`
	Name             types.String `tfsdk:"name"`
	OrgHandle        types.String `tfsdk:"org_handle"`
	Description      types.List   `tfsdk:"description"`
	Remarks          types.List   `tfsdk:"remarks"`
	Members          types.Set    `tfsdk:"members"`
	MembersByRef     types.Set    `tfsdk:"members_by_ref"`
	MPMembers        types.Set    `tfsdk:"mp_members"`
	POCs             types.Set    `tfsdk:"poc_links"`
	CreationDate     types.String `tfsdk:"creation_date"`
	LastModifiedDate types.String `tfsdk:"last_modified_date"`
}

func NewRouteSetResource() resource.Resource { return &routeSetResource{} }
func (r *routeSetResource) Metadata(_ context.Context, req resource.MetadataRequest, resp *resource.MetadataResponse) {
	resp.TypeName = req.ProviderTypeName + "_irr_route_set"
}
